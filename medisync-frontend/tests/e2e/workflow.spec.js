import { test, expect } from "@playwright/test";

const apiUrl = process.env.E2E_API_URL || "http://127.0.0.1:8001/api";
let fixture;
test.beforeAll(async ({ request }) => {
  const response = await request.post(`${apiUrl}/login`, { data: { email: "andi.saputra@medika.com", password: "password123" } });
  expect(response.ok()).toBeTruthy();
  const { token, user } = await response.json();
  const headers = { Authorization: `Bearer ${token}`, Accept: "application/json" };
  const created = await request.post(`${apiUrl}/patients`, { headers, data: { name: "QA Pasien Uji", rm_number: `RM-QA-${Date.now()}`, birth_date: "1994-05-15", gender: "Perempuan", allergies: "Alergi uji" } });
  expect(created.ok()).toBeTruthy();
  fixture = { patient: (await created.json()).data, doctor: user };
});

test("full doctor → pharmacy → saved BPJS → public tracking workflow", async ({ page }, testInfo) => {
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await page.screenshot({ path: testInfo.outputPath("login-desktop.png"), fullPage: true });
  const trackingButton = page.getByRole("button", { name: /Lacak pelayanan obat/ });
  expect((await trackingButton.boundingBox()).height).toBeGreaterThanOrEqual(64);
  await page.getByRole("button", { name: "Masuk", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Selamat datang/ })).toBeVisible();
  await page.getByRole("navigation").getByRole("button", { name: "Pasien", exact: true }).click();
  await page.getByPlaceholder(/Cari nama pasien/).fill(fixture.patient.name);
  await page.getByRole("button", { name: /Periksa/ }).first().click();
  await page.getByLabel("Keluhan", { exact: true }).fill("Keluhan pengujian antarmuka");
  await page.getByLabel("Riwayat Penyakit", { exact: true }).fill("Riwayat pengujian antarmuka");
  await page.getByLabel("Diagnosis", { exact: true }).fill("Diagnosis pengujian");
  await page.getByRole("button", { name: "Lanjut ke Resep", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Resep Elektronik", exact: true })).toBeVisible();
  await page.getByLabel("Nama Obat", { exact: true }).fill("Obat QA Uji");
  await page.getByLabel("Jumlah", { exact: true }).fill("10 tablet");
  await page.getByLabel("Dosis", { exact: true }).fill("Dosis pengujian");
  await page.getByLabel("Aturan Pakai", { exact: true }).fill("Aturan pengujian");
  await page.getByRole("button", { name: "Tinjau & sahkan resep", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Sahkan resep", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Resep berhasil disahkan", exact: true })).toBeVisible();
  const code = (await page.locator("main").innerText()).match(/MS-[A-Z0-9]{6}/)[0];
  await page.getByRole("button", { name: "Keluar", exact: true }).click();
  await page.getByRole("button", { name: "Admin Apoteker", exact: true }).click();
  await page.getByRole("button", { name: "Masuk", exact: true }).click();
  await expect(page.getByRole("navigation", { name: "Instalasi Farmasi" })).toBeVisible();
  await page.getByRole("button", { name: "Verifikasi BPJS", exact: true }).click();
  await page.getByRole("combobox").selectOption({ label: `${fixture.patient.name} · ${code}` });
  for (const checkbox of await page.getByRole("checkbox").all()) await checkbox.check();
  await page.getByLabel(/Catatan pemeriksaan/).fill("Dokumen QA sudah diperiksa");
  await page.getByRole("button", { name: "Simpan verifikasi lengkap", exact: true }).click();
  await expect(page.getByText("Verifikasi lengkap berhasil disimpan.", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("bpjs-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("bpjs-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "Antrean Resep", exact: true }).click();
  await page.getByRole("button", { name: "Verifikasi BPJS", exact: true }).click();
  await page.getByRole("combobox").selectOption({ label: `${fixture.patient.name} · ${code}` });
  for (const checkbox of await page.getByRole("checkbox").all()) await expect(checkbox).toBeChecked();
  await page.reload();
  await expect(page.getByRole("navigation", { name: "Instalasi Farmasi" })).toBeVisible();
  await page.getByRole("button", { name: "Verifikasi BPJS", exact: true }).click();
  await page.getByRole("combobox").selectOption({ label: `${fixture.patient.name} · ${code}` });
  for (const checkbox of await page.getByRole("checkbox").all()) await expect(checkbox).toBeChecked();
  await expect(page.getByLabel(/Catatan pemeriksaan/)).toHaveValue("Dokumen QA sudah diperiksa");
  await page.getByRole("button", { name: "Status Pelayanan", exact: true }).click();
  await page.getByRole("combobox").selectOption({ label: `${fixture.patient.name} · ${code}` });
  for (const action of ["Terima Resep", "Mulai Peracikan", "Siap Diserahkan", "Tandai Diserahkan"]) {
    await page.getByRole("button", { name: action, exact: true }).click();
    if (action === "Tandai Diserahkan") await page.getByRole("dialog").getByRole("button", { name: action, exact: true }).click();
  }
  await expect(page.getByRole("button", { name: "Tandai Diserahkan", exact: true }).first()).toBeDisabled();
  await page.getByRole("button", { name: "Keluar", exact: true }).click();
  await page.getByRole("button", { name: /Lacak pelayanan obat/ }).click();
  await page.getByLabel("Kode Tracking", { exact: true }).fill(code);
  await page.getByRole("button", { name: "Lacak status obat", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Diserahkan", exact: true })).toBeVisible();
  await expect(page.getByText(fixture.patient.name, { exact: true })).toBeVisible();
  await expect(page.getByText(fixture.doctor.name, { exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Obat QA Uji", exact: true })).toBeVisible();
  await expect(page.getByText("Aturan pengujian", { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("tracking-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: testInfo.outputPath("tracking-mobile.png"), fullPage: true });
  await page.getByRole("button", { name: "Kembali ke login", exact: true }).first().click();
  await expect(page.getByRole("heading", { name: "Masuk ke MediSync", exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

